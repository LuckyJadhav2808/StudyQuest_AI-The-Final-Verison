/**
 * Fast binary-search prefix lookup
 * Returns up to maxResults matching words for any prefix
 */
export function getAutocompleteSuggestions(prefix: string, maxResults: number = 6): string[] {
  if (!prefix || prefix.length < 2) return [];
  const query = prefix.toLowerCase().trim();
  
  const results: string[] = [];
  
  // Fast binary search to find starting index
  let low = 0;
  let high = AUTOCOMPLETE_WORDS.length - 1;
  let startIdx = -1;

  while (low <= high) {
    const mid = Math.floor((low + high) / 2);
    const word = AUTOCOMPLETE_WORDS[mid];
    
    if (word.startsWith(query)) {
      startIdx = mid;
      high = mid - 1; // Look for earlier occurrence
    } else if (word < query) {
      low = mid + 1;
    } else {
      high = mid - 1;
    }
  }

  if (startIdx === -1) return [];

  // Collect matching words
  for (let i = startIdx; i < AUTOCOMPLETE_WORDS.length && results.length < maxResults; i++) {
    const word = AUTOCOMPLETE_WORDS[i];
    if (word.startsWith(query)) {
      results.push(word);
    } else {
      break;
    }
  }

  return results;
}
